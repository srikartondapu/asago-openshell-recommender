"""Compile an agent sandbox manifest into OpenShell sandbox artifacts (least privilege).

Each policy section takes its values from the agent's manifest (what the agent declares it needs) or from
lab.yaml (paths and defaults that every sandbox needs to run at all). Outputs, in --out:
  policy.yaml            OpenShell sandbox policy (version 1)
  provider-profile.yaml  only when the manifest declares an MCP server (custom provider profile for its token)
  runtime.json           how to create/run the sandbox: providers to attach, token mode

usage:
  python compile.py --manifest ../examples/klarna-support/inputs/sandbox-manifest-refunds.yaml --out out/refunds
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent


def load(p: Path) -> dict:
    return yaml.safe_load(p.read_text())


def channels(m: dict) -> list[dict]:
    """Declared network channels: model, MCP servers, HTTP capabilities (all from the manifest)."""
    b = m["binaries"]
    out = [{"name": "model", "kind": "model", "host": m["model"]["host"], "port": m["model"]["port"],
            "binary": b[m["model"]["binary"]]}]
    for name, srv in m.get("servers", {}).items():
        tools = [c["id"] for c in m["capabilities"] if c["kind"] == "mcp_tool" and c.get("server") == name]
        out.append({"name": f"mcp_{name}", "kind": "mcp", "host": srv["host"], "port": srv["port"],
                    "path": srv.get("path", "/mcp"), "binary": b[srv["binary"]], "tools": tools})
    for c in m["capabilities"]:
        if c["kind"] == "http":
            out.append({"name": f"http_{c['id']}", "kind": "http", "host": c["host"], "port": c["port"],
                        "binary": b[c["binary"]], "methods": c.get("methods", ["GET"]), "path": c.get("path", "/**")})
    return out


def mcp_rules(ch: dict) -> list[dict]:
    return [{"allow": {"method": "tools/list"}},
            {"allow": {"method": "tools/call", "tool": {"any": ch["tools"]}}}]


def compile_policy(m: dict, lab: dict) -> tuple[dict, dict | None, dict]:
    chans = channels(m)

    # Network: only declared channels are reachable, each one by its own program (manifest).
    # Everything else is denied by default. Endpoints with L7 rules use enforcement=enforce (block, not audit).
    rules: dict = {}
    provider_profile = None
    for ch in chans:
        ep: dict = {"host": ch["host"], "port": ch["port"]}
        if ch["kind"] == "http":
            # HTTP capabilities: allow only the declared methods and path (manifest).
            ep.update(protocol="rest", enforcement="enforce",
                      rules=[{"allow": {"method": meth, "path": ch["path"]}} for meth in ch["methods"]])
        if ch["kind"] == "mcp":
            # MCP servers: the token is an OpenShell provider credential, so the sandbox only sees a placeholder.
            # The provider profile carries the endpoint (OpenShell merges it into the policy), with the
            # declared-tool allowlist. It must be an inspected endpoint.
            provider_profile = {
                "id": f"{m['agent']}-{m['variant']}-tools-token",
                "display_name": f"{m['agent']} {m['variant']} tool token",
                "description": "Bearer token for the agent's MCP tool server (generated by the OpenShell recommender)",
                "category": "other",
                "credentials": [{"name": "tool_token", "description": "MCP tool server bearer token",
                                 "env_vars": ["MIDOJO_TOOL_TOKEN"], "required": True,
                                 "auth_style": "bearer", "header_name": "Authorization"}],
                "endpoints": [{"host": ch["host"], "port": ch["port"], "path": ch["path"], "protocol": "mcp",
                               "enforcement": "enforce", "mcp": {"allow_all_known_mcp_methods": True},
                               "rules": mcp_rules(ch)}],
                "binaries": [ch["binary"]],
            }
            continue
        rules[ch["name"]] = {"endpoints": [ep], "binaries": [{"path": ch["binary"]}]}

    # Filesystem: writable = declared workspace (manifest) + system paths (lab.yaml).
    # Readable = system paths (lab.yaml) + declared read-only paths (manifest). The image workdir is not exposed.
    declared_rw = [p for c in m["capabilities"] if c["kind"] == "fs" for p in c.get("read_write", [])]
    declared_ro = [p for c in m["capabilities"] if c["kind"] == "fs" for p in c.get("read_only", [])]
    fs = {"include_workdir": False,
          "read_only": list(lab["system_read_only"]) + declared_ro,
          "read_write": declared_rw + list(lab["system_read_write"])}

    # Landlock is fixed (best effort). Process: the manifest's uid (lab.yaml default if the manifest sets none).
    policy = {"version": 1, "filesystem_policy": fs, "landlock": {"compatibility": "best_effort"}}
    uid = str(m.get("uid", lab["default_uid"]))
    policy["process"] = {"run_as_user": uid, "run_as_group": uid}
    policy["network_policies"] = rules

    # Runtime: the token is injected by the provider (token_mode "provider"); providers lists the profile above.
    runtime = {"image": m["image"], "token_mode": "provider",
               "providers": [provider_profile["id"]] if provider_profile else []}
    return policy, provider_profile, runtime


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--lab", type=Path, default=HERE / "lab.yaml")
    a = ap.parse_args()

    lab, manifest = load(a.lab), load(a.manifest)
    policy, profile, runtime = compile_policy(manifest, lab)

    a.out.mkdir(parents=True, exist_ok=True)
    head = f"# Generated by the OpenShell recommender compiler. manifest={a.manifest.name} least privilege from the manifest\n"
    (a.out / "policy.yaml").write_text(head + yaml.safe_dump(policy, sort_keys=False))
    if profile:
        (a.out / "provider-profile.yaml").write_text(head + yaml.safe_dump(profile, sort_keys=False))
    (a.out / "runtime.json").write_text(json.dumps(runtime, indent=2))
    print(f"{a.out}: {len(policy['network_policies'])} network rules, "
          f"provider={'yes' if profile else 'no'}, token_mode={runtime['token_mode']}")


if __name__ == "__main__":
    main()
